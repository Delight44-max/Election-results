-- ============================================================================
-- PostgreSQL migration reference for the Bincom election database
-- (bincomphptest, originally MySQL/phpMyAdmin format)
-- ============================================================================
-- This file is a readable, PostgreSQL-compatible rendering of the original
-- schema for reference and manual inspection. It documents the conversions
-- applied. IT IS NOT THE MECHANISM USED TO PROVISION THE DATABASE — Prisma
-- migrations (backend/prisma/schema.prisma + `prisma migrate deploy`) are the
-- source of truth. Use this file to understand what changed, or to run a
-- manual `psql` import if you ever need one outside of Prisma.
--
-- CONVERSIONS APPLIED (original -> PostgreSQL):
--   AUTO_INCREMENT              -> GENERATED BY DEFAULT AS IDENTITY
--   ENGINE=MyISAM / InnoDB      -> removed (Postgres has a single storage engine)
--   DEFAULT CHARSET=latin1      -> removed (Postgres databases are UTF-8)
--   backtick identifiers        -> double-quoted / unquoted lowercase identifiers
--   `int(11)` display widths    -> INTEGER (display widths are a MySQL-only, no-op concept)
--   0000-00-00 00:00:00 dates   -> NULL (not a legal Postgres timestamp)
--   MySQL comment/config lines  -> removed (SET NAMES, SET SQL_MODE, phpMyAdmin headers, etc.)
--
-- SCHEMA DECISIONS (see backend/prisma/schema.prisma header for full rationale):
--   - `lga.lga_id` and `ward.ward_id` are the dump's *business* identifiers used
--     as foreign keys elsewhere. `lga_id` is globally unique in this dataset and
--     is used as the real relation target for `ward.lga_id`, `polling_unit.lga_id`,
--     and `announced_lga_results` (whose `lga_name` column actually stores the
--     LGA's numeric id — confirmed against the data, not assumed).
--   - `ward_id` is only unique within an LGA, so it is kept as a descriptive
--     column rather than a relation target; `polling_unit.uniquewardid` (the
--     ward's global auto-increment id) is used as the real FK to `ward`.
--   - `announced_pu_results.polling_unit_uniqueid` matches `polling_unit.uniqueid`
--     and is modelled as a real foreign key.
-- ============================================================================

CREATE TABLE states (
  state_id    INTEGER PRIMARY KEY,
  state_name  VARCHAR(50) NOT NULL
);

CREATE TABLE lga (
  uniqueid          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lga_id            INTEGER NOT NULL UNIQUE,
  lga_name          VARCHAR(50) NOT NULL,
  state_id          INTEGER NOT NULL REFERENCES states(state_id),
  lga_description   TEXT,
  entered_by_user   VARCHAR(50),
  date_entered      TIMESTAMP,
  user_ip_address   VARCHAR(50)
);
CREATE INDEX idx_lga_state_id ON lga(state_id);

CREATE TABLE ward (
  uniqueid          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_id           INTEGER NOT NULL,
  ward_name         VARCHAR(50) NOT NULL,
  lga_id            INTEGER NOT NULL REFERENCES lga(lga_id),
  ward_description  TEXT,
  entered_by_user   VARCHAR(50),
  date_entered      TIMESTAMP,
  user_ip_address   VARCHAR(50)
);
CREATE INDEX idx_ward_lga_id ON ward(lga_id);

CREATE TABLE polling_unit (
  uniqueid                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  polling_unit_id           INTEGER NOT NULL,
  ward_id                   INTEGER NOT NULL,
  lga_id                    INTEGER NOT NULL REFERENCES lga(lga_id),
  uniquewardid              INTEGER REFERENCES ward(uniqueid),
  polling_unit_number       VARCHAR(50),
  polling_unit_name         VARCHAR(255),
  polling_unit_description  TEXT,
  lat                       VARCHAR(255),
  long                      VARCHAR(255),
  entered_by_user           VARCHAR(50),
  date_entered              TIMESTAMP,
  user_ip_address           VARCHAR(50)
);
CREATE INDEX idx_pu_lga_id ON polling_unit(lga_id);
CREATE INDEX idx_pu_uniquewardid ON polling_unit(uniquewardid);

CREATE TABLE party (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partyid     VARCHAR(11) NOT NULL UNIQUE,
  partyname   VARCHAR(50) NOT NULL
);

CREATE TABLE agentname (
  name_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  firstname               VARCHAR(255) NOT NULL,
  lastname                VARCHAR(255) NOT NULL,
  email                   VARCHAR(255),
  phone                   VARCHAR(20) NOT NULL,
  -- Nullable: some agent rows in the source dump reference a polling unit id that
  -- doesn't exist anywhere in `polling_unit` (a dangling reference already present
  -- in the original MySQL data, since MyISAM never enforced foreign keys).
  pollingunit_uniqueid    INTEGER REFERENCES polling_unit(uniqueid)
);
CREATE INDEX idx_agent_pu ON agentname(pollingunit_uniqueid);

CREATE TABLE announced_lga_results (
  result_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lga_id              INTEGER NOT NULL REFERENCES lga(lga_id), -- was mislabelled "lga_name" in the dump
  party_abbreviation  VARCHAR(10) NOT NULL,
  party_score         INTEGER NOT NULL,
  entered_by_user     VARCHAR(50),
  date_entered        TIMESTAMP NOT NULL,
  user_ip_address     VARCHAR(50)
);
CREATE INDEX idx_lga_results_lga ON announced_lga_results(lga_id);
CREATE INDEX idx_lga_results_party ON announced_lga_results(party_abbreviation);

CREATE TABLE announced_pu_results (
  result_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  polling_unit_uniqueid   INTEGER NOT NULL REFERENCES polling_unit(uniqueid),
  party_abbreviation      VARCHAR(10) NOT NULL,
  party_score             INTEGER NOT NULL,
  entered_by_user         VARCHAR(50),
  date_entered            TIMESTAMP NOT NULL,
  user_ip_address         VARCHAR(50)
);
CREATE INDEX idx_pu_results_pu ON announced_pu_results(polling_unit_uniqueid);
CREATE INDEX idx_pu_results_party ON announced_pu_results(party_abbreviation);

-- Present in the original dump with zero rows; kept for API/schema completeness.
CREATE TABLE announced_state_results (
  result_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  state_name          VARCHAR(50) NOT NULL,
  party_abbreviation  VARCHAR(10) NOT NULL,
  party_score         INTEGER NOT NULL,
  entered_by_user     VARCHAR(50),
  date_entered        TIMESTAMP NOT NULL,
  user_ip_address     VARCHAR(50)
);

CREATE TABLE announced_ward_results (
  result_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_name           VARCHAR(50) NOT NULL,
  party_abbreviation  VARCHAR(10) NOT NULL,
  party_score         INTEGER NOT NULL,
  entered_by_user     VARCHAR(50),
  date_entered        TIMESTAMP NOT NULL,
  user_ip_address     VARCHAR(50)
);

